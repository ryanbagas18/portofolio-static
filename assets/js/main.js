/**
 * Global function to get the current language
 */
function getCurrentLanguage() {
  return localStorage.getItem("portfolio_lang") || "en";
}

/**
 * Global function to change language and update UI
 */
function setLanguage(lang) {
  localStorage.setItem("portfolio_lang", lang);
  document.documentElement.lang = lang;
  updateUIContent(lang);
  updateActiveSwitcher(lang);

  // Custom event to notify other scripts (like project detail)
  const event = new CustomEvent("languageChanged", { detail: { lang: lang } });
  window.dispatchEvent(event);
}

/**
 * Update all elements with data-i18n attribute
 */
function updateUIContent(lang) {
  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (staticTranslations[lang][key]) {
      el.innerHTML = staticTranslations[lang][key];
    }
  });

  // Specifically handle the project list in index.html if it's there
  updateDynamicProjects(lang);
}

/**
 * Update the active state of language switcher buttons
 */
function updateActiveSwitcher(lang) {
  const buttons = document.querySelectorAll(".lang-switcher");
  buttons.forEach((btn) => {
    if (btn.getAttribute("data-lang") === lang) {
      btn.classList.add("active", "btn-primary");
      btn.classList.remove("btn-outline-primary");
    } else {
      btn.classList.remove("active", "btn-primary");
      btn.classList.add("btn-outline-primary");
    }
  });
}

/**
 * Update project cards on the main page if they are hardcoded
 * Actually, it's better to render them dynamically to handle i18n easily.
 */
function updateDynamicProjects(lang) {
  const container = document.querySelector("#projects .row.g-4");
  if (container && typeof projectsData !== "undefined") {
    renderProjectList(lang, container);
  }
}

/**
 * Render project list dynamically
 */
function renderProjectList(lang, container) {
  if (typeof projectsData === "undefined") return;

  container.innerHTML = projectsData
    .map((project) => {
      const title = project.title[lang];
      const org = project.organization[lang];
      const role = project.role[lang];
      const desc = project.description[lang];
      const btnText = staticTranslations[lang]["btn-project-detail"];

      return `
      <div class="col-md-6 col-lg-4">
        <div class="card border-0 shadow-sm h-100 project-card">
          <div class="ratio ratio-16x9">
            <img
              src="${project.thumbnail}"
              class="img-fluid rounded w-100"
              alt="${title}"
              style="
                object-fit: cover;
                image-rendering: -webkit-optimize-contrast;
                image-rendering: crisp-edges;
              "
            />
          </div>
          <div class="card-body d-flex flex-column p-4">
            <h5 class="card-title fw-bold mb-1">${title}</h5>
            <p class="text-muted small mb-2">${org} | ${role}</p>
            <p class="card-text text-secondary mb-3 flex-grow-1">${desc}</p>

            <div class="mb-3 d-flex flex-wrap gap-1">
              ${project.techStack
                .slice(0, 3)
                .map(
                  (tech) => `
                <span class="badge bg-primary-subtle text-primary border" style="font-size: 0.75rem">${tech}</span>
              `,
                )
                .join("")}
            </div>

            <a href="project-detail.html?id=${project.id}" class="btn btn-outline-primary btn-sm mt-auto w-100">
              ${btnText}<i class="bi bi-arrow-right ms-1"></i>
            </a>
          </div>
        </div>
      </div>
    `;
    })
    .join("");
}

// Initialize on load
document.addEventListener("DOMContentLoaded", () => {
  const currentLang = getCurrentLanguage();
  setLanguage(currentLang);

  // Add click listeners to switchers
  document.addEventListener("click", (e) => {
    if (e.target.classList.contains("lang-switcher")) {
      const lang = e.target.getAttribute("data-lang");
      setLanguage(lang);
    }
  });

  // 1. Create Back to Top Button
  const backToTopBtn = document.createElement("button");
  backToTopBtn.id = "backToTopBtn";
  backToTopBtn.innerHTML = '<i class="bi bi-arrow-up"></i>';
  backToTopBtn.setAttribute("aria-label", "Back to top");
  document.body.appendChild(backToTopBtn);

  window.addEventListener("scroll", () => {
    if (window.scrollY > 400) {
      backToTopBtn.style.display = "flex";
    } else {
      backToTopBtn.style.display = "none";
    }
  });

  backToTopBtn.addEventListener("click", () => {
    window.scrollTo({ top: 0, behavior: "smooth" });
  });

  // 2. Scroll Reveal Animation using IntersectionObserver
  const observerOptions = {
    threshold: 0.05,
    rootMargin: "0px 0px -30px 0px",
  };

  const observer = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("active");
        observer.unobserve(entry.target);
      }
    });
  }, observerOptions);

  // Automatically add .reveal class to cards for smooth entrance
  document.querySelectorAll(".card").forEach((el) => {
    el.classList.add("reveal");
    observer.observe(el);
  });
});
